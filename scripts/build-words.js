// Builds data/bn-words.js, the Bloom filter of Bangla words that repairs
// Banglish conversions (banglish.js, repair). Run once when the list
// changes:
//
//   node scripts/build-words.js path/to/words.txt
//
// The list used: github.com/tahmid02016/bangla-wordlist, words.txt,
// 451,348 words after NFC, released into the public domain (Unlicense).
// The list itself is not shipped, only the filter: 1% false positives,
// never a false negative.

const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');

const src = process.argv[2];
if (!src) { console.error('usage: node scripts/build-words.js words.txt'); process.exit(1); }

const sandbox = { self: {} };
vm.runInNewContext(fs.readFileSync(path.join(__dirname, '..', 'banglish.js'), 'utf8'), sandbox);
const { bloomBuild } = sandbox.self.UktiBanglish;

const words = [...new Set(fs.readFileSync(src, 'utf8').split(/\r?\n/).map(w => w.trim().normalize('NFC')).filter(w => /^[ঀ-৿]+$/.test(w)))];
const { m, k, bits } = bloomBuild(words, 0.01);
const b64 = Buffer.from(bits).toString('base64');
const out = `// Generated by scripts/build-words.js from ${words.length} Bangla words
// (github.com/tahmid02016/bangla-wordlist, public domain). Do not edit.
self.UKTI_WORDS = { n: ${words.length}, m: ${m}, k: ${k}, b64: '${b64}' };
`;
fs.writeFileSync(path.join(__dirname, '..', 'data', 'bn-words.js'), out);
console.log(`data/bn-words.js: ${words.length} words, ${m} bits, k=${k}, ${(out.length / 1024).toFixed(0)} KB`);
